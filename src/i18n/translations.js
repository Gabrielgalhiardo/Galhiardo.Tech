export const localizedPath = (pathname, language) => {
  const base = pathname.replace(/^\/en(?=\/|$)/, '') || '/';
  const portuguese = base.replace(/^\/projects(?=\/|$)/, '/projetos');
  return language === 'en'
    ? `/en${portuguese === '/' ? '' : portuguese.replace(/^\/projetos(?=\/|$)/, '/projects')}`
    : portuguese;
};
